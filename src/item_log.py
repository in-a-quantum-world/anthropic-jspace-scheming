#!/usr/bin/env python3
"""Write the item-level inclusion log requested by the external review: for
each model and run, every bank item with its outcome and the reason for it.

Run from repo root: python3 src/item_log.py > docs/item-log.md
"""
import glob
import json

BANK = "data/matched_distractors.json"


def main():
    bank = json.load(open(BANK))["items"]
    bank_qs = [it["q"] for it in bank]
    print("# Item-level inclusion log, week-1 matched-distractor run\n")
    print("Generated by `src/item_log.py`; regenerate after any new run. "
          "Outcomes: included (answered correctly, trajectories recorded), "
          "capability-filtered (honest answer wrong, preregistered exclusion 1), "
          "and not-complied (included, but excluded from sandbag-only metrics "
          "by exclusion 2).\n")
    for f in sorted(glob.glob("results/20261025-1052-week1/week1_*.json")):
        d = json.load(open(f))
        rows = {r["q"]: r for r in d["rows"]}
        print(f"\n## {d['choice']} ({d['model']})\n")
        print("| item | answer | outcome |")
        print("|---|---|---|")
        for q in bank_qs:
            a = next(it["a"] for it in bank if it["q"] == q)
            r = rows.get(q)
            if r is None:
                outcome = "capability-filtered (honest answer wrong)"
            elif not r["complied"]:
                outcome = f"not-complied (sandbag output contained the answer: {r['sandbag_out'][:30]!r})"
            else:
                outcome = "included"
            print(f"| {q[:60]} | {a} | {outcome} |")


if __name__ == "__main__":
    main()
